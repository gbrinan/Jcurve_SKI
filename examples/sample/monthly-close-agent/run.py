def main():
    global TR
    print("월간 실적 마감 및 경영보고 에이전트  (전략기획팀 · P-C2-1)\n")
    TR = Trace("월간 실적 마감 및 경영보고 에이전트",
               source="AX전략 워크샵 · 전략기획팀 · P-C2-1",
               lv4="실적관리", lv5="월간 실적 마감 및 경영보고")
    제출, 실적 = load("사업부제출"), load("월간실적")
    임계, 양식 = load("편차임계"), load("보고서양식")
    소명 = load_opt("소명접수")
    print(f"입력: {SRC.relative_to(PACK)} — 사업부 {len(제출)}곳 · 실적 항목 {len(실적)}건 · "
          f"임계 {len(임계)}종 · 소명 {len(소명)}건\n")
    TR.input("사업부", len(제출), "2026년 8월 실적 마감 · data/실적데이터.md")
    TR.input("실적항목", len(실적)).input("편차임계", len(임계))
    TR.input("소명", len(소명))

    취합 = 사업부실적취합(제출, 실적)

    # ── 갈림길 + 루프백 ────────────────────────────────────────────────
    회차, 요청 = 1, set()
    while True:
        편차, 초과 = 편차분석(취합, 실적, 임계, 소명 if 요청 else [], 회차)
        if not 초과:
            print(f"  ◆ 임계 초과 있음? → No · 경영보고서작성으로 진행 ({회차}회차에 탈출)")
            break
        if 회차 >= MAX회차:
            step("편차분석", f"❌ {MAX회차}회차까지 초과가 남아 멈춥니다 — 사람에게 넘깁니다")
            step("편차분석", "소명이 없거나 인정되지 않은 항목은 스킬이 해소할 수 없습니다")
            return 1
        print("  ◆ 임계 초과 있음? → Yes · 소명요청검토로 분기")
        요청 |= 소명요청검토(초과, 소명, 회차)
        회차 += 1

    보고서 = 경영보고서작성(양식, 편차, 취합)
    CEO보고상정(취합, 편차, 보고서, 회차)

    for l in TR.d["loops"]:
        l["cycles"] = 회차
    TR.done(f"루프백 {회차-1}회 (소명 L3) · 최종 {회차}회차에 임계초과 0 · "
            f"사람 확인 없이 상정된 것 없음")
    TR.save(OUT)
    print("  → out/trace.json (실행 기록 — 목업 화면이 이것을 읽습니다)")

    print(f"\n루프백 {회차-1}회 (소명 L3) · 최종 {회차}회차에 임계초과 0")
    print("사람 확인 없이 상정된 것: 없음")
    return 0


