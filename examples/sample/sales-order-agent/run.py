#!/usr/bin/env python3
"""E2E 시뮬레이션 — 6개 SKILL.md의 명세를 그대로 실행한다.

사용: python3 examples/sample/sales-order-agent/run.py

이 팩의 볼거리는 **루프백**이다. 여신한도점검에서 한도를 넘는 거래처가 나오면
여신조정요청으로 갔다가 다시 공급가능확인으로 되돌아온다. 물량이 줄면 공급도
여신도 다시 계산되기 때문이다. 초과가 0이 될 때까지 돈다.

입력은 `data/수주데이터.md` 하나다. 표마다 왜 그 값인지가 문장으로 붙어 있어
교육생이 값을 고쳐가며 흐름이 어디로 갈라지는지 볼 수 있다.

사람고유 지점은 자동으로 넘어가지 않는다. 물량 조정은 사람이 한 것으로 **표시만** 하고,
그 사실을 화면에 그대로 적는다. 수주 확정·출하 지시는 이 팩이 하지 않는다.
"""
import sys
from pathlib import Path

PACK = Path(__file__).resolve().parent
DATA, OUT = PACK / "data", PACK / "out"
SRC = DATA / "수주데이터.md"

# mdtable.py는 툴킷(check/)에 있다. 설치 위치가 어디든 찾도록 몇 군데를 본다.
for cand in (PACK.parents[2] / "check", PACK.parent / "check", PACK / "check"):
    if (cand / "mdtable.py").is_file():
        sys.path.insert(0, str(cand))
        break
else:
    sys.exit("mdtable.py를 찾지 못했습니다 — 툴킷의 check/ 폴더가 있어야 합니다.")
from mdtable import read_table, num   # noqa: E402
from trace import Trace               # noqa: E402

진척임계 = 0.80      # 판매계획 진척률이 이 아래면 미달 — agent-plan.md §3과 같아야 한다
집계상태 = "접수"    # 취소·보류는 집계에서 제외한다
MAX회차 = 5          # 무한 반복 방지. 넘으면 멈추고 사람에게 넘긴다.

TR = None   # main()에서 Trace로 채운다. 화면 목업이 읽는 기록.


def step(skill, msg):
    print(f"  [{skill}] {msg}")


def load(title):
    """수주데이터.md 안의 표 하나를 읽는다."""
    return read_table(SRC, title)


def load_opt(title):
    """있으면 읽고, 없거나 비어 있으면 빈 목록으로 본다.

    여신 예외승인이 한 건도 없는 달은 정상이다. 표가 비었다고 멈추지 않는다 —
    다만 '예외가 없다'와 '표를 못 읽었다'를 구분해 화면에 적는다.
    """
    try:
        return load(title)
    except KeyError:
        print(f"  (참고: 「{title}」 표가 비어 있거나 없습니다 — 해당 없음으로 봅니다)")
        return []


def write(name, rows, cols, note=""):
    """산출물도 마크다운 표로 쓴다 — 만든 것을 그대로 열어 볼 수 있게."""
    OUT.mkdir(exist_ok=True)
    lines = [f"# {Path(name).stem}", ""]
    if note:
        lines += [f"> {note}", ""]
    lines += ["| " + " | ".join(cols) + " |",
              "|" + "|".join("---" for _ in cols) + "|"]
    for r in rows:
        lines.append("| " + " | ".join(str(r.get(c, "")) for c in cols) + " |")
    lines.append("")
    (OUT / name).write_text("\n".join(lines), encoding="utf-8")
    print(f"  → out/{name} ({len(rows)}건)")


def 원(n):
    return f"{int(n):,}"


def 금액(주문량, 제품, 단가표):
    """주문 금액 = 주문량(kL) × 1000 × 기준단가(원/L)."""
    return int(주문량) * 1000 * num(단가표.get(제품, 0))


# ── 1. 판매계획확인 [자동] ─────────────────────────────────────────────
COLS_계획 = ["제품", "월간계획량", "누계실적", "진척률", "판정"]


def 판매계획확인(계획):
    rows = []
    for p in 계획:
        계, 실 = num(p["월간계획량"]), num(p["누계실적"])
        r = 실 / 계 if 계 else 0
        rows.append({"제품": p["제품"], "월간계획량": 계, "누계실적": 실,
                     "진척률": f"{r:.1%}", "판정": "미달" if r < 진척임계 else ""})
    미달 = [r for r in rows if r["판정"] == "미달"]
    step("판매계획확인", f"제품 {len(rows)}종 · 진척 미달 {len(미달)}종"
                        + (f" ({', '.join(r['제품'] for r in 미달)})" if 미달 else ""))
    TR.step("1. 판매계획확인", "자동",
            f"제품 {len(rows)}종의 계획 대비 진척을 확인했습니다. "
            f"진척률 {진척임계:.0%} 미만인 **미달 {len(미달)}종**입니다. "
            f"계획을 바꾸지는 않습니다 — 어디가 뒤처졌는지 보이게 만들 뿐입니다.")
    if 미달:
        TR.warn(f"판매계획 미달 {len(미달)}종 — "
                + ", ".join(f"{r['제품']}({r['진척률']})" for r in 미달)
                + ". 이 스킬은 계획도 주문도 조정하지 않습니다.")
    write("판매계획확인결과.md", rows, COLS_계획,
          f"진척률 {진척임계:.0%} 미만을 미달로 표시했습니다.")
    TR.file("out/판매계획확인결과.md", len(rows))
    return rows


# ── 2. 주문접수취합 [자동] → 주문취합결과.md ──────────────────────────
COLS_주문 = ["주문번호", "거래처코드", "거래처명", "제품", "주문량", "금액", "상태"]


def 주문접수취합(주문, 거래처, 단가표):
    이름 = {c["거래처코드"]: c["거래처명"] for c in 거래처}
    rows = []
    for o in 주문:
        량 = num(o["주문량"])
        rows.append({"주문번호": o["주문번호"], "거래처코드": o["거래처코드"],
                     "거래처명": 이름.get(o["거래처코드"], "(미등록)"),
                     "제품": o["제품"], "주문량": 량,
                     "금액": 금액(량, o["제품"], 단가표), "상태": o["상태"]})
    접수 = [r for r in rows if r["상태"] == 집계상태]
    제외 = [r for r in rows if r["상태"] != 집계상태]
    미등록 = [r for r in rows if r["거래처명"] == "(미등록)"]
    step("주문접수취합", f"주문 {len(rows)}건 · 접수 {len(접수)}건"
                        + (f" · 집계 제외 {len(제외)}건 (취소·보류)" if 제외 else ""))
    TR.step("2. 주문접수취합", "자동",
            f"주문 {len(rows)}건을 취합했습니다. 집계 대상은 **접수 {len(접수)}건**입니다."
            + (f" 취소·보류 {len(제외)}건은 **집계에서 빼되 지우지 않습니다** — "
               f"취소·보류는 접수와 다르고, 그렇다고 사라진 것도 아닙니다." if 제외 else ""))
    TR.table("주문취합결과", rows, COLS_주문,
             mark=lambda r: "na" if r["상태"] != 집계상태 else None)
    if 제외:
        TR.warn(f"집계 제외 {len(제외)}건 — "
                + ", ".join(f"{r['주문번호']}({r['상태']})" for r in 제외)
                + ". 최종 점검표에 남깁니다.")
    if 미등록:
        TR.warn(f"거래처마스터에 없는 주문 {len(미등록)}건 — 거래처명을 지어내지 않았습니다.")
    write("주문취합결과.md", rows, COLS_주문,
          "취소·보류는 집계에서 제외했습니다. 금액은 기준단가 기준이라 실제 청구액과 다를 수 있습니다.")
    TR.file("out/주문취합결과.md", len(rows))
    return rows, 접수


# ── 3. 공급가능확인 [증강] → 공급가능결과.md ── 루프백 대상 ────────────
COLS_공급 = ["제품", "가용재고", "생산예정", "공급가능", "주문합계", "과부족", "판정"]


def 공급가능확인(접수, 재고, 회차, 조정=None):
    주문합 = {}
    for r in 접수:
        량 = 조정.get(r["주문번호"], r["주문량"]) if 조정 else r["주문량"]
        주문합[r["제품"]] = 주문합.get(r["제품"], 0) + num(량)
    rows, 부족 = [], []
    for s in 재고:
        가용, 생산 = num(s["가용재고"]), num(s["생산예정"])
        가능 = 가용 + 생산                     # 공급가능량은 스킬이 더해서 만든다
        합 = 주문합.get(s["제품"], 0)
        차 = 가능 - 합
        rows.append({"제품": s["제품"], "가용재고": 가용, "생산예정": 생산,
                     "공급가능": 가능, "주문합계": 합, "과부족": 차,
                     "판정": "부족" if 차 < 0 else ""})
        if 차 < 0:
            부족.append(rows[-1])
    부족표기 = ", ".join(f"{r['제품']} {-r['과부족']}kL" for r in 부족)
    step("공급가능확인", f"[{회차}회차] 제품 {len(rows)}종 · 공급 부족 {len(부족)}종"
                        + (f" ({부족표기})" if 부족 else ""))
    step("공급가능확인", "부족분을 어느 주문에서 뺄지 정하지 않음 — 배분은 사람이 함")
    TR.cycle(회차).step(
        "3. 공급가능확인", "증강",
        f"제품 {len(rows)}종의 공급가능량(가용재고+생산예정)을 주문 합계와 맞췄습니다. "
        f"**공급 부족 {len(부족)}종**입니다."
        + (" 부족분을 어느 주문에서 뺄지는 **정하지 않습니다** — 배분은 영업담당이 합니다."
           if 부족 else ""))
    TR.table("공급가능결과", rows, COLS_공급,
             mark=lambda r: "diff" if r["판정"] == "부족" else None)
    if 부족:
        TR.warn("공급 부족 — "
                + ", ".join(f"{r['제품']} {-r['과부족']}kL" for r in 부족)
                + ". 주문을 임의로 줄이지 않고 그대로 두었습니다.")
    write("공급가능결과.md", rows, COLS_공급,
          "공급가능 = 가용재고 + 생산예정입니다. 부족분 배분은 하지 않았습니다.")
    TR.file("out/공급가능결과.md", len(rows))
    return rows, 부족


# ── 4. 여신한도점검 [증강] ── 갈림길 ───────────────────────────────────
COLS_여신 = ["거래처코드", "거래처명", "여신한도", "현재여신", "신규주문", "합계", "여유", "판정"]


def 여신한도점검(접수, 거래처, 단가표, 예외, 회차, 조정=None):
    승인 = {e["거래처코드"]: e["승인사유"] for e in 예외}
    신규 = {}
    for r in 접수:
        량 = 조정.get(r["주문번호"], r["주문량"]) if 조정 else r["주문량"]
        신규[r["거래처코드"]] = 신규.get(r["거래처코드"], 0) + 금액(량, r["제품"], 단가표)

    rows, 초과 = [], []
    for c in 거래처:
        코드 = c["거래처코드"]
        한도, 현재 = num(c["여신한도"]), num(c["현재여신"])
        새 = 신규.get(코드, 0)
        if 새 == 0:                       # 이번 달 주문이 없는 거래처는 판정하지 않는다
            continue
        합 = 현재 + 새
        넘음 = 합 > 한도
        판정 = ("예외승인" if 넘음 and 코드 in 승인 else "한도초과" if 넘음 else "")
        rows.append({"거래처코드": 코드, "거래처명": c["거래처명"], "여신한도": 한도,
                     "현재여신": 현재, "신규주문": 새, "합계": 합,
                     "여유": 한도 - 합, "판정": 판정})
        if 판정 == "한도초과":
            초과.append({**rows[-1], "초과액": 합 - 한도, "여유액": 한도 - 현재})
    예외건 = [r for r in rows if r["판정"] == "예외승인"]
    step("여신한도점검", f"[{회차}회차] 거래처 {len(rows)}곳 · 한도초과 {len(초과)}곳"
                        + (f" ({', '.join(d['거래처명'] for d in 초과)})" if 초과 else "")
                        + (f" · 예외승인 {len(예외건)}곳 (초과로 세지 않음)" if 예외건 else ""))
    TR.cycle(회차).fork(
        "4. 여신한도점검", "증강",
        [("한도 초과 있음? → Yes", "여신조정요청", len(초과) if 초과 else None),
         ("한도 초과 있음? → No", "수주확정품의", None)],
        note=f"거래처 {len(rows)}곳의 현재여신 + 신규주문을 한도와 맞췄습니다. "
             f"**한도초과 {len(초과)}곳**입니다."
             + (f" 예외승인 {len(예외건)}곳은 승인 기록이 있어 초과로 세지 않습니다 — "
                f"**승인 기록이 있는 것과 없는 것은 다릅니다.**" if 예외건 else ""),
        taken="여신조정요청" if 초과 else "수주확정품의")
    TR.table("여신점검결과", rows, COLS_여신,
             mark=lambda r: {"한도초과": "diff", "예외승인": "na"}.get(r["판정"]))
    if 예외건:
        TR.warn(f"여신 예외승인 적용 {len(예외건)}곳 — "
                + ", ".join(f"{r['거래처명']}: {승인[r['거래처코드']]}" for r in 예외건)
                + ". 승인 근거를 최종 점검표에 남깁니다.")
    write("여신점검결과.md", rows, COLS_여신,
          "예외승인 거래처는 초과로 세지 않았습니다. 금액은 기준단가 기준입니다.")
    TR.file("out/여신점검결과.md", len(rows))
    return rows, 초과


# ── 5. 여신조정요청 [사람고유] ── 루프백 ───────────────────────────────
def 여신조정요청(초과, 접수, 단가표, 회차):
    step("여신조정요청", f"⛔ 사람고유 — 초과 {len(초과)}곳의 목록과 근거만 만듦 "
                        f"(어느 주문을 얼마나 줄일지 정하지 않음)")
    for d in 초과:
        print(f"      · {d['거래처명']}({d['거래처코드']}) — 한도 {원(d['여신한도'])} vs "
              f"합계 {원(d['합계'])} = 초과 {원(d['초과액'])} (여유 {원(d['여유액'])})")
    print("      ⏸ 영업담당 조정 대기 … (시뮬레이션에서는 조정된 것으로 표시하고 진행)")
    step("여신조정요청", "↩ 공급가능확인으로 되돌아감 (탈출 조건: 한도초과 0)")
    TR.cycle(회차).halt(
        "5. 여신조정요청", "사람고유",
        f"한도초과 {len(초과)}곳의 목록과 근거만 만들었습니다. "
        f"**어느 주문을 얼마나 줄일지는 정하지 않았습니다.** 조정은 영업담당이 합니다.",
        checklist=[f"{d['거래처명']}({d['거래처코드']}) — 한도 {원(d['여신한도'])} vs "
                   f"합계 {원(d['합계'])} = 초과 {원(d['초과액'])} (여유 {원(d['여유액'])})"
                   for d in 초과])
    TR.warn("영업담당 조정 대기. 조정이 확정되면 공급가능확인으로 되돌아가 다시 맞춰봅니다.")
    TR.loop("여신조정요청", "공급가능확인", exit_cond="한도초과가 0이 되면")

    # 사람이 확정한 조정을 **표시만** 한다. 어느 주문을 줄일지는 이 코드가 정하지 않는다 —
    # 시뮬레이션에서는 그 거래처의 마지막 주문을 여유액 안으로 줄인 것으로 표시한다.
    조정 = {}
    for d in 초과:
        후보 = [r for r in 접수 if r["거래처코드"] == d["거래처코드"]]
        if not 후보:
            continue
        대상 = 후보[-1]
        단가 = num(단가표.get(대상["제품"], 0)) * 1000
        다른합 = sum(금액(r["주문량"], r["제품"], 단가표) for r in 후보[:-1])
        가능액 = max(0, d["여유액"] - 다른합)
        조정[대상["주문번호"]] = int(가능액 // 단가) if 단가 else 0
    return 조정


