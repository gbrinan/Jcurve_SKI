#!/usr/bin/env python3
"""E2E 시뮬레이션 — 6개 SKILL.md의 명세를 그대로 실행한다.

사용: python3 examples/sample/hr-appraisal-agent/run.py

이 팩의 볼거리는 **루프백**이다. 평가정합성검증에서 분포 이상이 나오면
이상조직조정요청으로 갔다가 다시 리더평가입력점검으로 되돌아온다.
분포가 가이드라인 안에 들어올 때까지 돈다 — 원본 워크샵이 평가 지연의
주요 원인으로 지목한 그 자리다.

입력은 `data/평가데이터.md` 하나다. 표마다 왜 그 값인지가 문장으로 붙어 있어
교육생이 값을 고쳐가며 흐름이 어디로 갈라지는지 볼 수 있다.

사람고유 지점은 자동으로 넘어가지 않는다. 조정은 사람이 한 것으로 **표시만** 하고,
그 사실을 화면에 그대로 적는다. 등급 확정·통보는 이 팩이 하지 않는다.
"""
import sys
from pathlib import Path

PACK = Path(__file__).resolve().parent
DATA, OUT = PACK / "data", PACK / "out"
SRC = DATA / "평가데이터.md"

# mdtable.py는 툴킷(check/)에 있다. 설치 위치가 어디든 찾도록 몇 군데를 본다.
for cand in (PACK.parents[2] / "check", PACK.parent / "check", PACK / "check"):
    if (cand / "mdtable.py").is_file():
        sys.path.insert(0, str(cand))
        break
else:
    sys.exit("mdtable.py를 찾지 못했습니다 — 툴킷의 check/ 폴더가 있어야 합니다.")
from mdtable import read_table   # noqa: E402
from trace import Trace          # noqa: E402

마감일 = "2026-11-20"     # 자기평가 제출 마감 — 평가일정 표와 같아야 한다
MAX회차 = 5               # 무한 반복 방지. 넘으면 멈추고 사람에게 넘긴다.

TR = None   # main()에서 Trace로 채운다. 화면 목업이 읽는 기록.


def step(skill, msg):
    print(f"  [{skill}] {msg}")


def load(title):
    """평가데이터.md 안의 표 하나를 읽는다."""
    return read_table(SRC, title)


def write(name, rows, cols, note=""):
    """산출물도 마크다운 표로 쓴다 — 만든 것을 그대로 열어 볼 수 있게."""
    OUT.mkdir(exist_ok=True)
    lines = [f"# {Path(name).stem}", ""]
    if note:
        lines += [f"> {note}", ""]
    lines += ["| " + " | ".join(cols) + " |",
              "|" + "|".join("---" for _ in cols) + "|"]
    for r in rows:
        lines.append("| " + " | ".join(str(r.get(c, "")) for c in cols) + " |")
    lines.append("")
    (OUT / name).write_text("\n".join(lines), encoding="utf-8")
    print(f"  → out/{name} ({len(rows)}건)")


def pct(n, d):
    return 0.0 if not d else n / d


# ── 1. 평가계획수립 [자동] ─────────────────────────────────────────────
def 평가계획수립(일정, 대상자):
    남은 = [r for r in 일정 if r["상태"] != "완료"]
    조직 = sorted({r["조직"] for r in 대상자})
    msg = (f"대상자 {len(대상자)}명 · 조직 {len(조직)}개 · "
           f"남은 단계 {len(남은)}개 (최종 마감 {일정[-1]['마감일']})")
    step("평가계획수립", msg)
    TR.step("1. 평가계획수립", "자동", msg + " 일정을 앞당기지는 못합니다.")
    return 조직


# ── 2. 자기평가취합 [자동] → 자기평가취합결과.md ───────────────────────
COLS_자기 = ["사번", "성명", "조직", "제출여부", "제출일", "상태"]


def 자기평가취합(대상자, 제출):
    by = {r["사번"]: r for r in 제출}
    rows = []
    for p in 대상자:
        s = by.get(p["사번"], {})
        여부 = s.get("제출여부", "미제출")
        일 = s.get("제출일", "")
        if 여부 != "제출":
            상태 = "미제출"
        elif 일 and 일 > 마감일:
            상태 = "지각제출"
        else:
            상태 = "정상"
        rows.append({"사번": p["사번"], "성명": p["성명"], "조직": p["조직"],
                     "제출여부": 여부, "제출일": 일, "상태": 상태})
    미제출 = [r for r in rows if r["상태"] == "미제출"]
    지각 = [r for r in rows if r["상태"] == "지각제출"]
    step("자기평가취합", f"제출 {len(rows) - len(미제출)}/{len(rows)}명"
                        + (f" · 미제출 {len(미제출)}명 (제출로 채우지 않음)" if 미제출 else "")
                        + (f" · 지각제출 {len(지각)}명" if 지각 else ""))
    TR.step("2. 자기평가취합", "자동",
            f"자기평가 제출 현황을 취합했습니다. 제출 **{len(rows) - len(미제출)}/{len(rows)}명**."
            + (f" 미제출 {len(미제출)}명은 제출로 채우지 않고 그대로 남깁니다 — "
               f"**제출하지 않은 것과 제출한 것은 다릅니다.**" if 미제출 else ""))
    if 미제출:
        TR.warn(f"자기평가 미제출 {len(미제출)}명 — "
                + ", ".join(f"{r['성명']}({r['사번']})" for r in 미제출)
                + ". 사유는 데이터에 적힌 것만 씁니다.")
    write("자기평가취합결과.md", rows, COLS_자기,
          f"제출 마감은 {마감일}입니다. 마감 후 제출은 지각제출로 표시했습니다.")
    TR.file("out/자기평가취합결과.md", len(rows))
    return rows


# ── 3. 리더평가입력점검 [증강] → 리더평가점검결과.md ───────────────────
COLS_점검 = ["사번", "성명", "조직", "평가리더", "등급", "근거기재", "점검결과"]


def 리더평가입력점검(대상자, 리더평가, 근거요구, 회차, 조정=None):
    필수 = [r["등급"] for r in 근거요구 if r["근거필수"] == "필수"]
    by = {r["사번"]: r for r in 리더평가}
    rows = []
    for p in 대상자:
        v = by.get(p["사번"], {})
        등급 = (v.get("등급") or "").strip()
        if 조정 and p["사번"] in 조정:      # 사람이 확정한 조정을 반영
            등급 = 조정[p["사번"]]
        근거 = (v.get("근거기재") or "").strip()
        if not 등급:
            결과 = "미입력"
        elif 등급 in 필수 and 근거 != "기재":
            결과 = "근거미기재"
        else:
            결과 = "정상"
        rows.append({"사번": p["사번"], "성명": p["성명"], "조직": p["조직"],
                     "평가리더": v.get("평가리더", ""), "등급": 등급 or "",
                     "근거기재": 근거, "점검결과": 결과})
    미입력 = [r for r in rows if r["점검결과"] == "미입력"]
    근거 = [r for r in rows if r["점검결과"] == "근거미기재"]
    step("리더평가입력점검", f"[{회차}회차] 입력 {len(rows) - len(미입력)}/{len(rows)}명"
                            + (f" · 미입력 {len(미입력)}명 (분포 계산에서 제외)" if 미입력 else "")
                            + (f" · 근거미기재 {len(근거)}명 ({'·'.join(필수)}등급)" if 근거 else ""))
    step("리더평가입력점검", "등급을 바꾸지 않음 — 점검까지")
    TR.cycle(회차).step(
        "3. 리더평가입력점검", "증강",
        f"리더 입력 **{len(rows) - len(미입력)}/{len(rows)}명**을 점검했습니다."
        + (f" 미입력 {len(미입력)}명은 B로 채우지 않고 **분포 계산에서 제외**합니다." if 미입력 else "")
        + (f" {'·'.join(필수)}등급 근거미기재 {len(근거)}명 — "
           f"**등급을 바꾸지는 않습니다.** 점검까지입니다." if 근거 else ""))
    TR.table("리더평가점검결과", rows, COLS_점검,
             mark=lambda r: {"미입력": "na", "근거미기재": "diff"}.get(r["점검결과"]))
    if 미입력:
        TR.warn(f"리더평가 미입력 {len(미입력)}명 — "
                + ", ".join(f"{r['성명']}({r['사번']})" for r in 미입력)
                + ". **입력이 없는 것과 낮은 등급은 다릅니다.**")
    write("리더평가점검결과.md", rows, COLS_점검,
          "미입력은 채우지 않았고, 근거미기재도 등급을 바꾸지 않았습니다.")
    TR.file("out/리더평가점검결과.md", len(rows))
    return rows


# ── 4. 평가정합성검증 [증강] ── 갈림길 ─────────────────────────────────
COLS_분포 = ["조직", "인원", "등급", "인원수", "비율", "허용상한", "판정"]


def 평가정합성검증(점검, 가이드, 회차):
    상한 = {r["등급"]: float(str(r["허용상한"]).rstrip("%")) / 100 for r in 가이드}
    등급들 = [r["등급"] for r in 가이드]
    조직별 = {}
    for r in 점검:
        if r["점검결과"] == "미입력":      # 분포 계산에서 제외 — 0으로 채우지 않는다
            continue
        조직별.setdefault(r["조직"], []).append(r)

    rows, 이상조직 = [], []
    for 조직 in sorted(조직별):
        인원 = len(조직별[조직])
        for g in 등급들:
            n = sum(1 for r in 조직별[조직] if r["등급"] == g)
            비율 = pct(n, 인원)
            초과 = 비율 > 상한.get(g, 1.0)
            rows.append({"조직": 조직, "인원": 인원, "등급": g, "인원수": n,
                         "비율": f"{비율:.1%}", "허용상한": f"{상한.get(g, 0):.0%}",
                         "판정": "상한초과" if 초과 else ""})
            if 초과:
                이상조직.append({"조직": 조직, "등급": g, "인원수": n, "인원": 인원,
                                "비율": f"{비율:.1%}", "상한": f"{상한.get(g, 0):.0%}"})
    이상목록 = sorted({d["조직"] for d in 이상조직})
    step("평가정합성검증", f"[{회차}회차] 조직 {len(조직별)}개 검증 · 분포 이상 {len(이상조직)}건"
                          + (f" ({', '.join(이상목록)})" if 이상목록 else ""))
    TR.cycle(회차).fork(
        "4. 평가정합성검증", "증강",
        [("분포 이상 있음? → Yes", "이상조직조정요청", len(이상조직) if 이상조직 else None),
         ("분포 이상 있음? → No", "등급확정통보", None)],
        note=f"조직 {len(조직별)}개의 등급 분포를 가이드라인 허용상한과 맞췄습니다. "
             f"**분포 이상 {len(이상조직)}건**입니다. 권장비율과의 차이만으로는 이상으로 보지 않습니다.",
        taken="이상조직조정요청" if 이상조직 else "등급확정통보")
    TR.table("분포검증결과", rows, COLS_분포,
             mark=lambda r: "diff" if r["판정"] == "상한초과" else None)
    write("분포검증결과.md", rows, COLS_분포,
          "허용상한을 넘은 것만 상한초과로 표시했습니다. 미입력자는 분모에서 제외했습니다.")
    TR.file("out/분포검증결과.md", len(rows))
    return rows, 이상조직


# ── 5. 이상조직조정요청 [사람고유] ── 루프백 ───────────────────────────
def 이상조직조정요청(이상조직, 점검, 회차):
    step("이상조직조정요청", f"⛔ 사람고유 — 이상 {len(이상조직)}건의 목록과 근거만 만듦 "
                            f"(누구의 등급을 내릴지 정하지 않음)")
    for d in 이상조직:
        print(f"      · {d['조직']} {d['등급']}등급 {d['인원수']}/{d['인원']}명 "
              f"= {d['비율']} (상한 {d['상한']})")
    print("      ⏸ 조직책임자 조정 대기 … (시뮬레이션에서는 조정된 것으로 표시하고 진행)")
    step("이상조직조정요청", "↩ 리더평가입력점검으로 되돌아감 (탈출 조건: 분포 이상 0)")
    TR.cycle(회차).halt(
        "5. 이상조직조정요청", "사람고유",
        f"분포 이상 {len(이상조직)}건의 목록과 근거만 만들었습니다. "
        f"**누구의 등급을 내릴지는 정하지 않았습니다.** 조정은 조직책임자가 합니다.",
        checklist=[f"{d['조직']} {d['등급']}등급 {d['인원수']}/{d['인원']}명 "
                   f"= {d['비율']} (상한 {d['상한']})" for d in 이상조직])
    TR.warn("조직책임자 조정 대기. 조정이 확정되면 리더평가입력점검으로 되돌아가 다시 점검합니다.")
    TR.loop("이상조직조정요청", "리더평가입력점검", exit_cond="분포 이상이 0이 되면")

    # 사람이 확정한 조정을 **표시만** 한다. 누구를 내릴지는 이 코드가 정하지 않는다 —
    # 시뮬레이션에서는 초과 등급의 마지막 1명을 한 단계 내린 것으로 표시한다.
    아래단계 = {"S": "A", "A": "B", "B": "C", "C": "D"}
    조정 = {}
    for d in 이상조직:
        후보 = [r for r in 점검 if r["조직"] == d["조직"] and r["등급"] == d["등급"]]
        if 후보 and d["등급"] in 아래단계:
            조정[후보[-1]["사번"]] = 아래단계[d["등급"]]
    return 조정


# ── 6. 등급확정통보 [사람고유] ── 여기서 멈춘다 ────────────────────────
def 등급확정통보(자기, 점검, 분포, 회차):
    미제출 = [r for r in 자기 if r["상태"] == "미제출"]
    지각 = [r for r in 자기 if r["상태"] == "지각제출"]
    미입력 = [r for r in 점검 if r["점검결과"] == "미입력"]
    근거 = [r for r in 점검 if r["점검결과"] == "근거미기재"]
    남은 = len(미제출) + len(지각) + len(미입력) + len(근거)
    lines = ["# 등급 확정·통보 전 점검표", "",
             "> ⛔ 여기서 멈춥니다. **에이전트는 등급을 확정하지 않았고, 누구에게도 통보하지 않았습니다.**",
             "> 인사담당 임원이 확인하고 직접 확정·통보해야 합니다.", "",
             f"분포 검증은 **{회차}회차**만에 이상 0에 도달했습니다.", "",
             f"## 남은 확인 사항 {남은}건", ""]
    for r in 미제출:
        lines.append(f"- [ ] **자기평가 미제출** — {r['성명']}({r['사번']}) {r['조직']}"
                     f" (제출한 것과 다릅니다)")
    for r in 미입력:
        lines.append(f"- [ ] **리더평가 미입력** — {r['성명']}({r['사번']}) {r['조직']}"
                     f" · 리더 {r['평가리더']} (분포 계산에서 제외됨)")
    for r in 근거:
        lines.append(f"- [ ] **근거 미기재** — {r['성명']}({r['사번']}) {r['등급']}등급"
                     f" · 리더 {r['평가리더']}")
    for r in 지각:
        lines.append(f"- [ ] **지각 제출 확인** — {r['성명']}({r['사번']}) {r['제출일']}")
    lines += ["", "---", "", "이 팩에는 등급 확정·통보 코드가 없습니다.",
              "", "## 최종 분포", ""]
    조직들 = sorted({r["조직"] for r in 분포})
    lines += ["| 조직 | 인원 | " + " | ".join(g for g in ("S", "A", "B", "C", "D")) + " |",
              "|---|---|" + "|".join("---" for _ in range(5)) + "|"]
    for 조직 in 조직들:
        인원 = next((r["인원"] for r in 분포 if r["조직"] == 조직), 0)
        cells = []
        for g in ("S", "A", "B", "C", "D"):
            m = next((r for r in 분포 if r["조직"] == 조직 and r["등급"] == g), None)
            cells.append(f"{m['인원수']}명 ({m['비율']})" if m else "—")
        lines.append(f"| {조직} | {인원}명 | " + " | ".join(cells) + " |")
    lines.append("")
    OUT.mkdir(exist_ok=True)
    (OUT / "확정전점검표.md").write_text("\n".join(lines), encoding="utf-8")
    step("등급확정통보", f"⛔ 사람고유 — 점검표 {남은}건만 만들고 멈춤")
    print("  → out/확정전점검표.md")
    chk = ([f"자기평가 미제출 — {r['성명']}({r['사번']}) {r['조직']}" for r in 미제출]
           + [f"리더평가 미입력 — {r['성명']}({r['사번']}) {r['조직']} · 리더 {r['평가리더']}"
              for r in 미입력]
           + [f"근거 미기재 — {r['성명']}({r['사번']}) {r['등급']}등급" for r in 근거]
           + [f"지각 제출 확인 — {r['성명']}({r['사번']}) {r['제출일']}" for r in 지각])
    TR.cycle(None).halt(
        "6. 등급확정통보", "사람고유",
        f"**여기서 멈췄습니다.** 에이전트는 등급을 확정하지 않았고, 누구에게도 통보하지 않았습니다. "
        f"분포 검증은 **{회차}회차**만에 이상 0에 도달했고, 확정 전 확인할 것 **{남은}건**이 남았습니다.",
        actions=["등급 확정 및 통보", f"점검 항목 {남은}건 확인", "평가리더에게 반려"],
        checklist=chk)
    TR.file("out/확정전점검표.md")


def main():
    global TR
    print("연간 성과평가 운영 에이전트  (인사본부 인사운영팀 · P-B2-1)\n")
    TR = Trace("연간 성과평가 운영 에이전트",
               source="AX전략 워크샵 · 인사본부 인사운영팀 · P-B2-1",
               lv4="평가·보상", lv5="연간 성과평가 운영")
    일정, 대상자 = load("평가일정"), load("평가대상자")
    제출, 리더평가 = load("자기평가제출"), load("리더평가입력")
    가이드, 근거요구 = load("등급분포가이드라인"), load("근거요구등급")
    print(f"입력: {SRC.relative_to(PACK)} — 대상자 {len(대상자)}명 · 자기평가 {len(제출)}건 · "
          f"리더평가 {len(리더평가)}건 · 가이드라인 {len(가이드)}등급\n")
    TR.input("평가대상자", len(대상자), "2026년 연간 성과평가 · data/평가데이터.md")
    TR.input("자기평가", len(제출)).input("리더평가", len(리더평가))
    TR.input("분포가이드라인", len(가이드))

    평가계획수립(일정, 대상자)
    자기 = 자기평가취합(대상자, 제출)

    # ── 갈림길 + 루프백 ────────────────────────────────────────────────
    회차, 조정 = 1, {}
    while True:
        점검 = 리더평가입력점검(대상자, 리더평가, 근거요구, 회차, 조정)
        분포, 이상조직 = 평가정합성검증(점검, 가이드, 회차)
        if not 이상조직:
            print(f"  ◆ 분포 이상 있음? → No · 등급확정통보로 진행 ({회차}회차에 탈출)")
            break
        if 회차 >= MAX회차:
            step("평가정합성검증", f"❌ {MAX회차}회차까지 이상이 남아 멈춥니다 — 사람에게 넘깁니다")
            return 1
        print("  ◆ 분포 이상 있음? → Yes · 이상조직조정요청으로 분기")
        조정.update(이상조직조정요청(이상조직, 점검, 회차))
        회차 += 1

    등급확정통보(자기, 점검, 분포, 회차)

    for l in TR.d["loops"]:
        l["cycles"] = 회차
    TR.done(f"루프백 {회차-1}회 (분포조정) · 최종 {회차}회차에 분포 이상 0 · "
            f"사람 확인 없이 확정·통보된 것 없음")
    TR.save(OUT)
    print("  → out/trace.json (실행 기록 — 목업 화면이 이것을 읽습니다)")

    print(f"\n루프백 {회차-1}회 (분포조정) · 최종 {회차}회차에 분포 이상 0")
    print("사람 확인 없이 확정·통보된 것: 없음")
    return 0


