#!/usr/bin/env python3
"""E2E 시뮬레이션 — 7개 SKILL.md의 명세를 그대로 실행한다.

사용: python3 examples/sample/quarterly-close-agent/run.py

이 팩의 볼거리는 **루프백**이다. 계정검증대사에서 차이가 나면 차이분석조정으로 갔다가
다시 계정검증대사로 되돌아온다. 차이가 0이 될 때까지 돈다 — 원본 워크샵이
결산 지연의 주요 원인으로 지목한 그 자리(L4)다.

입력은 `data/결산데이터.md` 하나다. 표마다 왜 그 값인지가 문장으로 붙어 있어
교육생이 값을 고쳐가며 흐름이 어디로 갈라지는지 볼 수 있다.

사람고유 지점은 자동으로 넘어가지 않는다. 조정 확정은 사람이 한 것으로 **표시만** 하고,
그 사실을 화면에 그대로 적는다.
"""
import sys
from pathlib import Path

PACK = Path(__file__).resolve().parent
DATA, OUT = PACK / "data", PACK / "out"
SRC = DATA / "결산데이터.md"

# mdtable.py는 툴킷(check/)에 있다. 설치 위치가 어디든 찾도록 몇 군데를 본다.
for cand in (PACK.parents[2] / "check", PACK.parent / "check", PACK / "check"):
    if (cand / "mdtable.py").is_file():
        sys.path.insert(0, str(cand))
        break
else:
    sys.exit("mdtable.py를 찾지 못했습니다 — 툴킷의 check/ 폴더가 있어야 합니다.")
from mdtable import read_table, num   # noqa: E402
from trace import Trace          # noqa: E402

이상임계 = 0.30      # agent-plan.md §3 · CONTRACT.md threshold와 같아야 한다
설명임계 = 0.20
MAX회차 = 5          # 무한 반복 방지. 넘으면 멈추고 사람에게 넘긴다.


TR = None   # main()에서 Trace로 채운다. 화면 목업이 읽는 기록.


def step(skill, msg):
    print(f"  [{skill}] {msg}")


def load(title):
    """결산데이터.md 안의 표 하나를 읽는다."""
    return read_table(SRC, title)


def write(name, rows, cols, note=""):
    """산출물도 마크다운 표로 쓴다 — 만든 것을 그대로 열어 볼 수 있게."""
    OUT.mkdir(exist_ok=True)
    lines = [f"# {Path(name).stem}", ""]
    if note:
        lines += [f"> {note}", ""]
    lines += ["| " + " | ".join(cols) + " |",
              "|" + "|".join("---" for _ in cols) + "|"]
    for r in rows:
        lines.append("| " + " | ".join(str(r.get(c, "")) for c in cols) + " |")
    lines.append("")
    (OUT / name).write_text("\n".join(lines), encoding="utf-8")
    print(f"  → out/{name} ({len(rows)}건)")


def 만원(n):
    return f"{int(n):,}"


# ── 1. 결산일정수립 [증강] ─────────────────────────────────────────────
def 결산일정수립(cal):
    대기 = [c for c in cal if c["상태"] != "완료"]
    msg = (f"결산캘린더 {len(cal)}행 · 미완료 {len(대기)}건 "
           f"(마감일 {cal[-1]['마감일']} — PP-2 T+5일)")
    step("결산일정수립", msg)
    TR.step("1. 결산일정수립", "증강", msg)
    TR.warn("PP-2 [WAIT/높음] 결산 마감 일정 촉박(T+5일) — 일정을 앞당기지는 못합니다. "
            "남은 일수를 보이게 만들 뿐입니다.")
    return 대기


# ── 2. 원장잔액수집 [자동] → 잔액수집결과.md ──────────────────────────
COLS_잔액 = ["계정코드", "계정명", "당기잔액", "전기잔액", "증감률", "이상여부"]


def 원장잔액수집(ledger, subs):
    rows = []
    for a in ledger:
        전, 당 = num(a["전기잔액"]), num(a["당기잔액"])
        if 전 == 0:                                  # 0으로 나누지 않는다
            증감, 이상 = "", "신규계정"
        else:
            r = (당 - 전) / abs(전)
            증감 = f"{r:+.1%}"
            뒤집힘 = (전 > 0) != (당 > 0)
            이상 = "이상" if (abs(r) > 이상임계 or 뒤집힘) else ""
        rows.append({"계정코드": a["계정코드"], "계정명": a["계정명"],
                     "당기잔액": 당, "전기잔액": 전, "증감률": 증감, "이상여부": 이상})
    미수신 = [s["계열사명"] for s in subs if s["수신여부"] != "수신"]
    이상건 = [r for r in rows if r["이상여부"]]
    step("원장잔액수집", f"계정 {len(rows)}개 · 이상/신규 {len(이상건)}건")
    TR.step("2. 원장잔액수집", "자동",
            f"계정 {len(rows)}개를 읽고 이상/신규 {len(이상건)}건을 표시했습니다 "
            f"(전기 대비 ±{이상임계:.0%} 초과 또는 부호 반전).")
    if 미수신:
        step("원장잔액수집", f"⚠️ 계열사 미수신 {len(미수신)}곳: {', '.join(미수신)} "
                            f"— 0으로 채우지 않고 합계에서 제외 (PP-6)")
        TR.warn(f"계열사 미수신 {len(미수신)}곳 — {', '.join(미수신)}. "
                f"0으로 채우지 않고 합계에서 제외했습니다. (PP-6 [WAIT/높음])")
    write("잔액수집결과.md", rows, COLS_잔액, "전기 대비 ±30% 초과 또는 부호 반전을 이상으로 표시했습니다.")
    TR.file("out/잔액수집결과.md", len(rows))
    return rows, 미수신


# ── 3. 조정분개작성 [증강] → 조정분개장.md ────────────────────────────
COLS_분개 = ["분개번호", "계정코드", "차변", "대변", "사유", "상태"]


def 조정분개작성(잔액, 사유사전):
    # 아는 사유만 쓴다. 사전에 없는 계정은 지어내지 않고 사람에게 넘긴다.
    사유표 = {r["계정코드"]: r["사유"] for r in 사유사전}
    rows, n = [], 0
    for r in 잔액:
        if not r["이상여부"]:
            continue
        n += 1
        사유 = 사유표.get(r["계정코드"], "")
        차 = abs(num(r["당기잔액"]) - num(r["전기잔액"]))
        rows.append({"분개번호": f"ADJ-3Q-{n:03d}", "계정코드": r["계정코드"],
                     "차변": 차 if 차 > 0 else 0, "대변": 0,
                     "사유": 사유 or "사유확인필요",
                     "상태": "초안" if 사유 else "사유확인필요"})
    확인필요 = [r for r in rows if r["상태"] == "사유확인필요"]
    step("조정분개작성", f"조정분개 초안 {len(rows)}건"
                        + (f" · 사유확인필요 {len(확인필요)}건 (사유를 지어내지 않음)" if 확인필요 else ""))
    step("조정분개작성", "검토·승인(A-A2-1-3-3)은 하지 않음 — 초안까지")
    TR.step("3. 조정분개작성", "증강",
            f"조정분개 초안 {len(rows)}건."
            + (f" 그중 {len(확인필요)}건은 사유를 알 수 없어 **지어내지 않았습니다.**"
               if 확인필요 else "")
            + " 검토·승인(A-A2-1-3-3)은 하지 않습니다 — 초안까지입니다.")
    TR.table("조정분개장.md", rows, COLS_분개,
             mark=lambda r: "diff" if r["상태"] == "사유확인필요" else None)
    TR.file("out/조정분개장.md", len(rows))
    write("조정분개장.md", rows, COLS_분개, "초안입니다. 검토·승인은 하지 않았습니다.")
    return rows


# ── 4. 주석초안작성 [증강] → 주석초안.md ──────────────────────────────
COLS_주석 = ["주석번호", "주석항목", "전기금액", "당기금액", "증감률", "상태"]
주석매핑 = {"5": "1010", "7": "1110", "9": "1210", "14": "2110", "18": "4010"}


def 주석초안작성(전기주석, 잔액):
    by = {r["계정코드"]: r for r in 잔액}
    rows = []
    for n_ in 전기주석:
        코드 = 주석매핑.get(n_["주석번호"])
        acc = by.get(코드)
        if acc is None:
            rows.append({"주석번호": n_["주석번호"], "주석항목": n_["주석항목"],
                         "전기금액": n_["전기금액"], "당기금액": "", "증감률": "",
                         "상태": "신규항목"})
            continue
        전, 당 = num(n_["전기금액"]), abs(num(acc["당기잔액"]))
        r = (당 - 전) / 전 if 전 else 0
        rows.append({"주석번호": n_["주석번호"], "주석항목": n_["주석항목"],
                     "전기금액": 전, "당기금액": 당, "증감률": f"{r:+.1%}",
                     "상태": "설명필요" if abs(r) > 설명임계 else "초안"})
    설명 = [r for r in rows if r["상태"] == "설명필요"]
    step("주석초안작성", f"주석 {len(rows)}개 · 설명필요 {len(설명)}건 (전기 대비 ±{설명임계:.0%} 초과)")
    step("주석초안작성", "검토·확정(A-A2-1-4-3)은 하지 않음 — 초안까지")
    TR.step("4. 주석초안작성", "증강",
            f"주석 {len(rows)}개에 당기 숫자를 채웠습니다. 전기 대비 ±{설명임계:.0%}를 넘는 "
            f"설명필요 {len(설명)}건. 전기주석에 없는 항목은 숫자를 채우지 않고 `신규항목`으로 남깁니다.")
    TR.file("out/주석초안.md", len(rows))
    write("주석초안.md", rows, COLS_주석, "전기 항목 구조를 그대로 쓰고 당기 숫자만 채웠습니다.")
    return rows


# ── 5. 계정검증대사 [증강] ── 갈림길 ───────────────────────────────────
COLS_대사 = ["계정코드", "계정명", "원장잔액", "확인잔액", "차이", "상태", "회차"]


def 계정검증대사(잔액, 확인서, 회차, 조정반영=None):
    by = {r["계정코드"]: r for r in 잔액}
    합 = {}
    for c in 확인서:
        if c["수신여부"] != "수신":
            합.setdefault(c["계정코드"], None)
            continue
        합[c["계정코드"]] = 합.get(c["계정코드"]) or 0
        합[c["계정코드"]] += num(c["확인잔액"])

    rows, 차이건 = [], []
    for 코드, 확인 in 합.items():
        acc = by.get(코드)
        if acc is None:
            continue
        원장 = num(acc["당기잔액"])
        if 확인 is None:
            rows.append({"계정코드": 코드, "계정명": acc["계정명"], "원장잔액": 원장,
                         "확인잔액": "", "차이": "", "상태": "확인서미수신", "회차": 회차})
            continue
        차 = 원장 - 확인
        if 조정반영 and 코드 in 조정반영:      # 사람이 확정한 조정을 반영
            차 = 0
        상태 = "일치" if 차 == 0 else "차이"
        rows.append({"계정코드": 코드, "계정명": acc["계정명"], "원장잔액": 원장,
                     "확인잔액": 확인, "차이": 차, "상태": 상태, "회차": 회차})
        if 차 != 0:
            차이건.append(rows[-1])

    미수신 = [r for r in rows if r["상태"] == "확인서미수신"]
    step("계정검증대사", f"[{회차}회차] 대사 {len(rows)}계정 · 차이 {len(차이건)}건"
                        + (f" · 확인서미수신 {len(미수신)}건 (차이로 세지 않음)" if 미수신 else ""))
    TR.cycle(회차).fork(
        "5. 계정검증대사", "증강",
        [("차이 발견? → Yes", "차이분석조정", len(차이건) if 차이건 else None),
         ("차이 발견? → No", "결산마감", None)],
        note=f"외부확인서와 SAP 원장을 계정별로 맞췄습니다. **차이 {len(차이건)}건**입니다.",
        taken="차이분석조정" if 차이건 else "결산마감")
    TR.table("대사결과", rows, COLS_대사,
             mark=lambda r: {"차이": "diff", "확인서미수신": "na"}.get(r["상태"]))
    if 미수신:
        TR.warn(f"확인서 미수신 {len(미수신)}건 — 차이로 세지 않습니다. "
                f"**차이가 없는 것과 확인할 수 없는 것은 다릅니다.**")
    return rows, 차이건


# ── 6. 차이분석조정 [사람고유] ── 루프백 ───────────────────────────────
def 차이분석조정(차이건, 회차):
    step("차이분석조정", f"⛔ 사람고유 — 차이 {len(차이건)}건의 목록과 근거만 만듦 "
                        f"(조정 금액을 정하지 않음)")
    for d in 차이건:
        print(f"      · {d['계정코드']} {d['계정명']} — 원장 {만원(d['원장잔액'])} vs "
              f"확인 {만원(d['확인잔액'])} = 차이 {만원(d['차이'])}")
    print(f"      ⏸ 결산담당 확정 대기 … (시뮬레이션에서는 확정된 것으로 표시하고 진행)")
    step("차이분석조정", f"↩ 계정검증대사로 되돌아감 (탈출 조건: 차이 0)")
    TR.cycle(회차).halt(
        "6. 차이분석조정", "사람고유",
        f"차이 {len(차이건)}건의 목록과 근거만 만들었습니다. **조정 금액은 정하지 않았습니다.**",
        checklist=[f"{d['계정코드']} {d['계정명']} — 원장 {만원(d['원장잔액'])} vs "
                   f"확인 {만원(d['확인잔액'])} = 차이 {만원(d['차이'])}" for d in 차이건])
    TR.warn("결산담당 확정 대기. 조정이 확정되면 계정검증대사로 되돌아가 다시 맞춰봅니다.")
    TR.loop("차이분석조정", "계정검증대사", exit_cond="차이가 0이 되면")
    return {d["계정코드"] for d in 차이건}


# ── 7. 결산마감 [사람고유] ── 여기서 멈춘다 ────────────────────────────
def 결산마감(미수신계열사, 대사, 주석, 분개, 회차):
    확인서미수신 = [r for r in 대사 if r["상태"] == "확인서미수신"]
    설명필요 = [r for r in 주석 if r["상태"] == "설명필요"]
    사유필요 = [r for r in 분개 if r["상태"] == "사유확인필요"]
    남은 = len(미수신계열사) + len(확인서미수신) + len(설명필요) + len(사유필요)
    lines = ["# 결산 마감 전 점검표", "",
             "> ⛔ 여기서 멈춥니다. **에이전트는 원장을 잠그지 않았고, 마감 전표도 처리하지 않았습니다.**",
             "> 회계관리팀장이 확인하고 SAP에서 직접 Lock 해야 마감입니다.", "",
             f"대사는 **{회차}회차**만에 차이 0에 도달했습니다.", "",
             f"## 남은 확인 사항 {남은}건", ""]
    for s in 미수신계열사:
        lines.append(f"- [ ] **계열사 미수신** — {s} (PP-6)")
    for r in 확인서미수신:
        lines.append(f"- [ ] **확인서 미수신** — {r['계정코드']} {r['계정명']}"
                     f" (차이 없음이 아니라 확인 불가)")
    for r in 설명필요:
        lines.append(f"- [ ] **주석 설명 필요** — 주석{r['주석번호']} {r['주석항목']} ({r['증감률']})")
    for r in 사유필요:
        lines.append(f"- [ ] **조정 사유 확인** — {r['분개번호']} 계정 {r['계정코드']}")
    lines += ["", "---", "", "이 팩에는 마감 전표 처리·원장 Lock 코드가 없습니다."]
    OUT.mkdir(exist_ok=True)
    (OUT / "마감점검표.md").write_text("\n".join(lines), encoding="utf-8")
